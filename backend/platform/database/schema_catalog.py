from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class ColumnSpec:
    name: str
    sql_type: str
    constraints: str
    description: str


@dataclass(frozen=True)
class IndexSpec:
    name: str
    columns: tuple[str, ...]
    unique: bool = False
    where: str = ""


@dataclass(frozen=True)
class TableSpec:
    name: str
    domain: str
    purpose: str
    columns: tuple[ColumnSpec, ...]
    indexes: tuple[IndexSpec, ...] = ()
    notes: tuple[str, ...] = ()


def c(name: str, sql_type: str, constraints: str, description: str) -> ColumnSpec:
    return ColumnSpec(name, sql_type, constraints, description)


def idx(name: str, *columns: str, unique: bool = False, where: str = "") -> IndexSpec:
    return IndexSpec(name, tuple(columns), unique, where)


def tenant_entity(
    name: str,
    domain: str,
    purpose: str,
    id_name: str,
    columns: tuple[ColumnSpec, ...],
    indexes: tuple[IndexSpec, ...] = (),
    notes: tuple[str, ...] = (),
) -> TableSpec:
    return TableSpec(
        name=name,
        domain=domain,
        purpose=purpose,
        columns=(
            c(id_name, "UUID", "PRIMARY KEY DEFAULT gen_random_uuid()", "服务端生成的稳定主键。"),
            c("tenant_id", "UUID", "NOT NULL REFERENCES platform_tenants(tenant_id) ON DELETE CASCADE", "所属租户。"),
            *columns,
            c("created_by", "UUID", "REFERENCES platform_user_profiles(user_id) ON DELETE SET NULL", "创建人。"),
            c("created_at", "TIMESTAMPTZ", "NOT NULL DEFAULT now()", "创建时间，统一 UTC。"),
            c("updated_at", "TIMESTAMPTZ", "NOT NULL DEFAULT now()", "最后更新时间，统一 UTC。"),
            c("lock_version", "BIGINT", "NOT NULL DEFAULT 0 CHECK (lock_version >= 0)", "乐观锁版本。"),
        ),
        indexes=(idx(f"idx_{name}_tenant_updated", "tenant_id", "updated_at", id_name), *indexes),
        notes=notes,
    )



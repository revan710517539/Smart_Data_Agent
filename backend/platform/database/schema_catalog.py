def validate_catalog(tables: tuple[TableSpec, ...] = TABLES) -> None:
    names = [table.name for table in tables]
    if len(names) != 99:
        raise ValueError(f"Expected 99 production tables, found {len(names)}")
    if len(names) != len(set(names)):
        raise ValueError("Duplicate table names in production schema catalog")
    for table in tables:
        if not table.columns:
            raise ValueError(f"Table {table.name} has no columns")
        real_columns = [column.name for column in table.columns if column.name]
        if len(real_columns) != len(set(real_columns)):
            raise ValueError(f"Table {table.name} has duplicate columns")
        if not any("PRIMARY KEY" in column.constraints for column in table.columns):
            raise ValueError(f"Table {table.name} has no primary key")


validate_catalog()
